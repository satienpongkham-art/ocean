/** คืนค่า tier พร้อมสลับ Health Happy เป็นตัวทดแทนอัตโนมัติถ้าปิดรับแล้ว */
export function resolveTier(pkg, tierKey, isClosed) {
  const t = pkg.tiers[tierKey];
  if (!t) return null;
  const items = t.items.map((it) => {
    if (isClosed(it.plan) && it.plan === 'health-happy') return { ...HEALTH_HAPPY_ALT[tierKey], replaced: 'health-happy' };
    return it;
  });
  return { ...t, items };
}
