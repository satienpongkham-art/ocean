/** ข้อมูลการแนบสัญญา: สัญญาเพิ่มเติม ↔ สัญญาหลัก (จากข้อมูลแผนในแอป) */
export function attachInfo(PLANS, PLAN) {
  const riders = PLANS.filter((p) => p.kind === 'rider');
  const mains = PLANS.filter((p) => p.kind === 'main' && p.cat !== 'accident');
  const recMain = (r) => {
    const set = new Set((r.pairs || []).filter((x) => PLAN[x]?.kind === 'main'));
    for (const m of mains) if ((m.pairs || []).includes(r.id)) set.add(m.id);
    return [...set].map((x) => PLAN[x]);
  };
  const recRiders = (m) => {
    const set = new Set((m.pairs || []).filter((x) => PLAN[x]?.kind === 'rider'));
    for (const r of riders) if ((r.pairs || []).includes(m.id)) set.add(r.id);
    return [...set].map((x) => PLAN[x]);
  };
  const mustText = (r) => (r.specs || []).find(([k]) => k.startsWith('ต้องแนบ'))?.[1] || 'แบบประกันหลักของ AIA';
  return { riders, mains, recMain, recRiders, mustText };
}

