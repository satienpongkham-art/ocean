/** คิดว่าเข้ากรณีไหน: { claims, simpleClaims, simpleAmt, generalAmt, premium } → { rate, hits } */
export function copayCheck({ simpleClaims = 0, simpleAmt = 0, generalClaims = 0, generalAmt = 0, premium = 0 }) {
  const p = Math.max(1, +premium || 0);
  const r1 = (simpleAmt / p) * 100, r2 = (generalAmt / p) * 100;
  const c1 = simpleClaims >= 3 && r1 >= 200;
  const c2 = generalClaims >= 3 && r2 >= 400;
  return { r1: Math.round(r1), r2: Math.round(r2), c1, c2, rate: c1 && c2 ? 50 : c1 || c2 ? 30 : 0 };
}

