/** หาสติกเกอร์ที่เข้ากับข้อความ (คำยาวสุดที่เจอ) → code | null */
export function suggestEmoji(text = '') {
  let best = null, len = 0; const t = text.toLowerCase();
  for (const [code, , , kw] of EMOJI) for (const k of kw.split('|')) if (k.length > len && t.includes(k.toLowerCase())) { best = code; len = k.length; }
  return best;
}
